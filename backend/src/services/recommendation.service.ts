import type { RecommendationItem } from '../types/api.js';

const recommendations: RecommendationItem[] = [
  {
    id: 'REC-001',
    type: 'replenish',
    productId: 'SKU-001',
    storeId: 'STORE-01',
    suggestedAction: 'Replenish 120 units of Avocado before weekend demand spikes.',
    confidence: 0.86,
    status: 'draft',
  },
  {
    id: 'REC-002',
    type: 'markdown',
    productId: 'SKU-005',
    storeId: 'STORE-04',
    suggestedAction: 'Apply markdown to 30% of berries after 4 days remaining shelf life.',
    confidence: 0.74,
    status: 'approved',
  },
];

export const recommendationService = {
  async list() {
    return recommendations;
  },

  async generate(payload: Record<string, unknown>) {
    const item: RecommendationItem = {
      id: `REC-${Date.now()}`,
      type: (payload.actionType as RecommendationItem['type']) || 'replenish',
      productId: String(payload.productId || 'SKU-UNKNOWN'),
      storeId: String(payload.storeId || 'STORE-01'),
      suggestedAction: String(payload.reason || 'Candidate recommendation generated by orchestration layer.'),
      confidence: 0.82,
      status: 'draft',
    };
    recommendations.unshift(item);
    return item;
  },

  async approve(recommendationId: string, payload: Record<string, unknown>) {
    const match = recommendations.find((item) => item.id === recommendationId);
    if (!match) {
      throw new Error('Recommendation not found');
    }
    match.status = payload.approved === false ? 'rejected' : 'approved';
    return match;
  },

  async reject(recommendationId: string, payload: Record<string, unknown>) {
    const match = recommendations.find((item) => item.id === recommendationId);
    if (!match) {
      throw new Error('Recommendation not found');
    }
    match.status = 'rejected';
    return { ...match, comments: payload.comments || 'Rejected by manager' };
  },
};
