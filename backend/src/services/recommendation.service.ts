import {
  ActionType as PrismaActionType,
  PlannerDecision,
  type Prisma,
  RecommendationStatus as PrismaRecommendationStatus,
} from '@prisma/client';
import { env } from '../config/env.js';
import prisma from '../config/prisma.js';
import { recommendationSeed } from '../lib/dev-data.js';
import { HttpError, isPrismaErrorCode, requireDatabase } from '../lib/errors.js';
import type { RecommendationRecord, RecommendationStatus } from '../types/api.js';
import { writeAuditLog } from './audit.service.js';

const actionToPrisma: Record<RecommendationRecord['actionType'], PrismaActionType> = {
  replenish: PrismaActionType.REPLENISH,
  markdown: PrismaActionType.MARKDOWN,
  transfer: PrismaActionType.TRANSFER,
};
const actionFromPrisma: Record<PrismaActionType, RecommendationRecord['actionType']> = {
  [PrismaActionType.REPLENISH]: 'replenish',
  [PrismaActionType.MARKDOWN]: 'markdown',
  [PrismaActionType.TRANSFER]: 'transfer',
};
const statusFromPrisma: Record<PrismaRecommendationStatus, RecommendationStatus> = {
  [PrismaRecommendationStatus.DRAFT]: 'draft',
  [PrismaRecommendationStatus.APPROVED]: 'approved',
  [PrismaRecommendationStatus.REJECTED]: 'rejected',
  [PrismaRecommendationStatus.EXECUTED]: 'executed',
  [PrismaRecommendationStatus.FAILED]: 'failed',
};

type RecommendationRow = Prisma.RecommendationGetPayload<{ include: { decisions: true } }>;

function mapRecommendation(row: RecommendationRow): RecommendationRecord {
  return {
    id: row.id,
    storeId: row.storeId,
    productId: row.productId,
    actionType: actionFromPrisma[row.actionType],
    status: statusFromPrisma[row.status],
    confidence: row.confidence.toNumber(),
    quantity: row.quantity ?? 0,
    reason: row.reason,
    evidence: row.evidence ?? '',
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
    decisionHistory: (row.decisions ?? []).map((decision) => ({
      actor: decision.actor,
      decision: decision.decision.toLowerCase(),
      at: decision.createdAt.toISOString(),
    })),
  };
}

function demoOnly(): boolean {
  return env.demoMode;
}

async function recordRejectedTransition(
  id: string,
  actor: string,
  action: string,
  error: HttpError,
): Promise<void> {
  await prisma.auditLog.create({
    data: {
      actor,
      action,
      entityType: 'recommendation',
      entityId: id,
      recommendationId: error.statusCode === 404 ? null : id,
      details: { outcome: 'rejected', statusCode: error.statusCode, reason: error.message },
    },
  });
}

export const recommendationService = {
  async list(): Promise<RecommendationRecord[]> {
    if (demoOnly()) return recommendationSeed;
    requireDatabase(env.databaseUrl);
    const rows = await prisma.recommendation.findMany({
      include: { decisions: { orderBy: { createdAt: 'asc' } } },
      orderBy: { createdAt: 'desc' },
      take: 200,
    });
    return rows.map(mapRecommendation);
  },

  async getById(id: string): Promise<RecommendationRecord | null> {
    if (demoOnly()) return recommendationSeed.find((item) => item.id === id) ?? null;
    requireDatabase(env.databaseUrl);
    const row = await prisma.recommendation.findUnique({
      where: { id },
      include: { decisions: { orderBy: { createdAt: 'asc' } } },
    });
    return row ? mapRecommendation(row) : null;
  },

  async create(payload: {
    storeId: string;
    productId: string;
    actionType: RecommendationRecord['actionType'];
    quantity?: number;
    reason?: string;
    confidence?: number;
    evidence?: string;
  }): Promise<RecommendationRecord> {
    if (demoOnly()) {
      const now = new Date().toISOString();
      const next: RecommendationRecord = {
        id: `REC-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
        storeId: payload.storeId,
        productId: payload.productId,
        actionType: payload.actionType,
        status: 'draft',
        confidence: payload.confidence ?? 0.8,
        quantity: payload.quantity ?? 0,
        reason: payload.reason ?? 'Generated by demo planner',
        evidence: payload.evidence ?? '',
        createdAt: now,
        updatedAt: now,
        decisionHistory: [{ actor: 'system', decision: 'created', at: now }],
      };
      recommendationSeed.unshift(next);
      return next;
    }
    requireDatabase(env.databaseUrl);

    const created = await prisma.$transaction(async (tx) => {
      if (!(await tx.store.findUnique({ where: { id: payload.storeId }, select: { id: true } }))) {
        throw new HttpError('Store not found', 404);
      }
      if (!(await tx.product.findUnique({ where: { id: payload.productId }, select: { id: true } }))) {
        throw new HttpError('Product not found', 404);
      }
      const row = await tx.recommendation.create({
        data: {
          storeId: payload.storeId,
          productId: payload.productId,
          actionType: actionToPrisma[payload.actionType],
          confidence: payload.confidence ?? 0.8,
          quantity: payload.quantity ?? null,
          reason: payload.reason ?? 'Generated by backend planner workflow',
          evidence: payload.evidence,
          actions: {
            create: {
              productId: payload.productId,
              actionType: actionToPrisma[payload.actionType],
              quantity: payload.quantity,
            },
          },
          decisions: { create: { actor: 'system', decision: PlannerDecision.CREATED } },
        },
        include: { decisions: { orderBy: { createdAt: 'asc' } } },
      });
      await tx.recommendationRevision.create({
        data: {
          recommendationId: row.id,
          version: 1,
          actor: 'system',
          snapshot: {
            actionType: payload.actionType,
            quantity: payload.quantity ?? null,
            reason: payload.reason ?? 'Generated by backend planner workflow',
            confidence: payload.confidence ?? 0.8,
            evidence: payload.evidence ?? null,
          },
        },
      });
      await writeAuditLog(tx, {
        actor: 'system',
        action: 'recommendation_created',
        entityType: 'recommendation',
        entityId: row.id,
        recommendationId: row.id,
      });
      return row;
    });
    return mapRecommendation(created);
  },

  async approve(id: string, actor = 'planner', notes?: string): Promise<RecommendationRecord> {
    if (demoOnly()) {
      const row = recommendationSeed.find((item) => item.id === id);
      if (!row) throw new HttpError('Recommendation not found', 404);
      if (row.status !== 'draft') throw new HttpError('Only draft recommendations can be approved', 409);
      row.status = 'approved';
      row.updatedAt = new Date().toISOString();
      row.decisionHistory.push({ actor, decision: 'approved', at: row.updatedAt });
      return row;
    }
    requireDatabase(env.databaseUrl);
    try {
      return await prisma.$transaction(async (tx) => {
      const result = await tx.recommendation.updateMany({
        where: { id, status: PrismaRecommendationStatus.DRAFT },
        data: { status: PrismaRecommendationStatus.APPROVED },
      });
      if (!result.count) {
        const exists = await tx.recommendation.findUnique({ where: { id }, select: { id: true } });
        throw new HttpError(exists ? 'Only draft recommendations can be approved' : 'Recommendation not found', exists ? 409 : 404);
      }
      await tx.plannerDecisionRecord.create({ data: { recommendationId: id, actor, decision: PlannerDecision.APPROVED, notes } });
      await writeAuditLog(tx, {
        actor,
        action: 'recommendation_approved',
        entityType: 'recommendation',
        entityId: id,
        recommendationId: id,
        details: notes ? { notes } : undefined,
      });
      const row = await tx.recommendation.findUniqueOrThrow({
        where: { id },
        include: { decisions: { orderBy: { createdAt: 'asc' } } },
      });
      return mapRecommendation(row);
      });
    } catch (error) {
      if (error instanceof HttpError && [404, 409].includes(error.statusCode)) {
        await recordRejectedTransition(id, actor, 'recommendation_approval_denied', error);
      }
      throw error;
    }
  },

  async reject(id: string, actor = 'planner', notes?: string): Promise<RecommendationRecord> {
    if (demoOnly()) {
      const row = recommendationSeed.find((item) => item.id === id);
      if (!row) throw new HttpError('Recommendation not found', 404);
      if (row.status !== 'draft') throw new HttpError('Only draft recommendations can be rejected', 409);
      row.status = 'rejected';
      row.updatedAt = new Date().toISOString();
      row.decisionHistory.push({ actor, decision: 'rejected', at: row.updatedAt });
      return row;
    }
    requireDatabase(env.databaseUrl);
    try {
      return await prisma.$transaction(async (tx) => {
      const result = await tx.recommendation.updateMany({
        where: { id, status: PrismaRecommendationStatus.DRAFT },
        data: { status: PrismaRecommendationStatus.REJECTED },
      });
      if (!result.count) {
        const exists = await tx.recommendation.findUnique({ where: { id }, select: { id: true } });
        throw new HttpError(exists ? 'Only draft recommendations can be rejected' : 'Recommendation not found', exists ? 409 : 404);
      }
      await tx.plannerDecisionRecord.create({ data: { recommendationId: id, actor, decision: PlannerDecision.REJECTED, notes } });
      await writeAuditLog(tx, {
        actor,
        action: 'recommendation_rejected',
        entityType: 'recommendation',
        entityId: id,
        recommendationId: id,
        details: notes ? { notes } : undefined,
      });
      const row = await tx.recommendation.findUniqueOrThrow({
        where: { id },
        include: { decisions: { orderBy: { createdAt: 'asc' } } },
      });
      return mapRecommendation(row);
      });
    } catch (error) {
      if (error instanceof HttpError && [404, 409].includes(error.statusCode)) {
        await recordRejectedTransition(id, actor, 'recommendation_rejection_denied', error);
      }
      throw error;
    }
  },

  async modify(
    id: string,
    updates: Partial<Pick<RecommendationRecord, 'actionType' | 'quantity' | 'reason'>>,
    actor = 'planner',
    notes?: string,
  ): Promise<RecommendationRecord> {
    if (demoOnly()) {
      const row = recommendationSeed.find((item) => item.id === id);
      if (!row) throw new HttpError('Recommendation not found', 404);
      if (row.status !== 'draft') throw new HttpError('Only draft recommendations can be modified', 409);
      Object.assign(row, updates, { updatedAt: new Date().toISOString() });
      row.decisionHistory.push({ actor, decision: 'modified', at: row.updatedAt });
      return row;
    }
    requireDatabase(env.databaseUrl);
    try {
      return await prisma.$transaction(async (tx) => {
      const data = {
        ...(updates.actionType ? { actionType: actionToPrisma[updates.actionType] } : {}),
        ...(updates.quantity !== undefined ? { quantity: updates.quantity } : {}),
        ...(updates.reason ? { reason: updates.reason } : {}),
      };
      const updated = await tx.recommendation.updateMany({
        where: { id, status: PrismaRecommendationStatus.DRAFT },
        data,
      });
      if (!updated.count) {
        const existing = await tx.recommendation.findUnique({ where: { id }, select: { id: true } });
        throw new HttpError(existing ? 'Only draft recommendations can be modified' : 'Recommendation not found', existing ? 409 : 404);
      }
      const row = await tx.recommendation.findUniqueOrThrow({ where: { id } });
      const revisionCount = await tx.recommendationRevision.count({ where: { recommendationId: id } });
      await tx.recommendationRevision.create({
        data: {
          recommendationId: id,
          version: revisionCount + 1,
          actor,
          snapshot: {
            actionType: actionFromPrisma[row.actionType],
            quantity: row.quantity,
            reason: row.reason,
            confidence: row.confidence.toNumber(),
            evidence: row.evidence,
          },
        },
      });
      await tx.plannerDecisionRecord.create({ data: { recommendationId: id, actor, decision: PlannerDecision.MODIFIED, notes } });
      if (updates.actionType || updates.quantity !== undefined) {
        await tx.recommendationAction.create({
          data: {
            recommendationId: id,
            productId: row.productId,
            actionType: row.actionType,
            quantity: row.quantity,
          },
        });
      }
      await writeAuditLog(tx, {
        actor,
        action: 'recommendation_modified',
        entityType: 'recommendation',
        entityId: id,
        recommendationId: id,
        details: { ...data, notes },
      });
      const result = await tx.recommendation.findUniqueOrThrow({
        where: { id },
        include: { decisions: { orderBy: { createdAt: 'asc' } } },
      });
      return mapRecommendation(result);
      }, { isolationLevel: 'Serializable' });
    } catch (error) {
      if (error instanceof HttpError && [404, 409].includes(error.statusCode)) {
        await recordRejectedTransition(id, actor, 'recommendation_modification_denied', error);
      }
      throw error;
    }
  },

  async execute(id: string, actor = 'planner'): Promise<{ recommendation: RecommendationRecord; executed: boolean; reason?: string }> {
    if (demoOnly()) {
      const row = recommendationSeed.find((item) => item.id === id);
      if (!row) throw new HttpError('Recommendation not found', 404);
      if (row.status !== 'approved') return { recommendation: row, executed: false, reason: 'Recommendation must be approved before execution' };
      row.status = 'executed';
      row.updatedAt = new Date().toISOString();
      row.decisionHistory.push({ actor, decision: 'executed', at: row.updatedAt });
      return { recommendation: row, executed: true };
    }
    requireDatabase(env.databaseUrl);
    try {
      return await prisma.$transaction(async (tx) => {
      const record = await tx.recommendation.findUnique({
        where: { id },
        include: { decisions: { orderBy: { createdAt: 'asc' } }, execution: true },
      });
      if (!record) throw new HttpError('Recommendation not found', 404);
      if (record.status !== PrismaRecommendationStatus.APPROVED) {
        await writeAuditLog(tx, {
          actor,
          action: 'recommendation_execution_denied',
          entityType: 'recommendation',
          entityId: id,
          recommendationId: id,
          details: { status: record.status },
        });
        return {
          recommendation: mapRecommendation(record),
          executed: false,
          reason: record.status === PrismaRecommendationStatus.EXECUTED ? 'Recommendation has already been executed' : 'Recommendation must be approved before execution',
        };
      }
      const updated = await tx.recommendation.updateMany({
        where: { id, status: PrismaRecommendationStatus.APPROVED },
        data: { status: PrismaRecommendationStatus.EXECUTED },
      });
      if (!updated.count) {
        const current = await tx.recommendation.findUniqueOrThrow({
          where: { id },
          include: { decisions: { orderBy: { createdAt: 'asc' } }, execution: true },
        });
        return {
          recommendation: mapRecommendation(current),
          executed: false,
          reason: current.status === PrismaRecommendationStatus.EXECUTED ? 'Recommendation has already been executed' : 'Recommendation is no longer approved',
        };
      }
      await tx.executionRecord.create({
        data: { recommendationId: id, status: 'succeeded', payload: { simulated: true } },
      });
      await tx.plannerDecisionRecord.create({ data: { recommendationId: id, actor, decision: PlannerDecision.EXECUTED } });
      await writeAuditLog(tx, {
        actor,
        action: 'recommendation_executed',
        entityType: 'recommendation',
        entityId: id,
        recommendationId: id,
        details: { simulated: true },
      });
      const result = await tx.recommendation.findUniqueOrThrow({
        where: { id },
        include: { decisions: { orderBy: { createdAt: 'asc' } } },
      });
      return { recommendation: mapRecommendation(result), executed: true };
      }, { isolationLevel: 'Serializable' });
    } catch (error) {
      if (isPrismaErrorCode(error, 'P2034')) {
        const current = await prisma.recommendation.findUnique({
          where: { id },
          include: { decisions: { orderBy: { createdAt: 'asc' } } },
        });
        if (current?.status === PrismaRecommendationStatus.EXECUTED) {
          return {
            recommendation: mapRecommendation(current),
            executed: false,
            reason: 'Recommendation has already been executed',
          };
        }
      }
      throw error;
    }
  },
};
