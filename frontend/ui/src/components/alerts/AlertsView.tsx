import React, { useEffect, useState } from 'react';
import { useAuth } from '../../context/AuthContext';
import { api } from '../../lib/api';
import { AlertTier, ExpiryAlert } from '../../types';
import { StatusBadge } from '../common/StatusBadge';

interface AlertsViewProps {
  onNavigateToRecommendation?: (recId: string) => void;
}

export const AlertsView: React.FC<AlertsViewProps> = ({ onNavigateToRecommendation }) => {
  const { selectedStore } = useAuth();
  const [selectedTier, setSelectedTier] = useState<AlertTier | 'ALL'>('ALL');
  const [alerts, setAlerts] = useState<ExpiryAlert[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let active = true;
    setLoading(true);
    setAlerts([]);
    setError(null);
    api.getAlerts(selectedStore)
      .then((result) => {
        if (active) {
          setAlerts(result);
          setError(null);
        }
      })
      .catch((requestError: unknown) => {
        if (active) {
          setAlerts([]);
          setError(requestError instanceof Error ? requestError.message : 'The backend request failed.');
        }
      })
      .finally(() => {
        if (active) setLoading(false);
      });
    return () => {
      active = false;
    };
  }, [selectedStore]);

  const filteredAlerts = alerts.filter((alt) => {
    if (selectedStore !== 'ALL' && alt.storeId !== selectedStore) return false;
    if (selectedTier !== 'ALL' && alt.tier !== selectedTier) return false;
    return true;
  });

  const tiers: (AlertTier | 'ALL')[] = [
    'ALL',
    'Critical',
    'At Risk',
    'Monitor',
    'No Current Risk',
  ];

  return (
    <div className="space-y-6">
      {error && (
        <div role="alert" className="rounded-xl border border-red-200 bg-red-50 p-4 text-sm text-red-800">
          Unable to load backend expiry alerts: {error}
        </div>
      )}
      {loading && <div role="status" className="text-sm text-slate-500">Loading backend expiry alerts…</div>}

      {/* Explanatory Notice */}
      <div className="p-4 rounded-2xl bg-emerald-50/80 border border-emerald-200/80 flex items-start gap-3">
        <div className="w-5 h-5 rounded-full bg-emerald-600 text-white flex items-center justify-center shrink-0 mt-0.5 text-xs font-bold">
          i
        </div>
        <div className="text-xs text-slate-700">
          <span className="font-bold text-emerald-950">
            Backend expiry alert:
          </span>{' '}
          These risk scores use the backend expiry-window calculation. They are not generated by the FastAPI ML model, and demand/value projections are not provided by this endpoint.
        </div>
      </div>

      {/* Tier Filter Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 bg-white p-4 rounded-2xl border border-emerald-900/10 shadow-xs">
        <div className="flex items-center gap-1.5 flex-wrap">
          <span className="text-xs font-bold text-slate-500 mr-2 uppercase tracking-wider text-[10px]">
            Filter Alert Tier:
          </span>
          {tiers.map((t) => (
            <button
              key={t}
              onClick={() => setSelectedTier(t)}
              className={`px-3 py-1 rounded-xl text-xs font-semibold transition-all cursor-pointer ${
                selectedTier === t
                  ? 'bg-[#062314] text-white shadow-2xs'
                  : 'bg-slate-50 text-slate-600 hover:bg-slate-100 border border-slate-200'
              }`}
            >
              {t === 'ALL' ? 'All Alert Tiers' : t}
            </button>
          ))}
        </div>

        <div className="text-xs text-slate-500 font-medium">
          Showing <span className="font-bold text-slate-800">{filteredAlerts.length}</span> active alert signals
        </div>
      </div>

      {/* Alert Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
        {filteredAlerts.map((alert: ExpiryAlert) => (
          <div
            key={alert.id}
            className="bg-white rounded-3xl p-5 border border-emerald-900/10 shadow-xs flex flex-col justify-between hover:shadow-md transition-all"
          >
            <div>
              {/* Header */}
              <div className="flex items-center justify-between mb-3">
                <StatusBadge status={alert.tier} />
                <span className="font-mono text-xs font-extrabold text-slate-900 bg-slate-50 px-2 py-0.5 rounded-lg border border-slate-200">
                  Risk Score: {alert.riskScore}/100
                </span>
              </div>

              {/* Title & Batch */}
              <h3 className="text-base font-bold text-slate-900 leading-snug">
                {alert.productName}
              </h3>
              <p className="text-xs text-slate-500 mt-0.5 mb-3">
                Batch <span className="font-mono font-bold text-slate-800">{alert.batchId}</span> • {alert.storeName}
              </p>

              {/* Metrics Grid */}
              <div className="grid grid-cols-2 gap-2 py-3 border-y border-slate-100 text-xs mb-3">
                <div>
                  <span className="text-slate-400 block text-[10px] uppercase font-bold">Units At Risk</span>
                  <span className="font-mono font-extrabold text-slate-900 text-sm">
                    {alert.unitsAtRisk} units
                  </span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[10px] uppercase font-bold">Days to Expiry</span>
                  <span className="font-mono font-extrabold text-slate-900 text-sm">
                    {alert.daysToExpiry} {alert.daysToExpiry === 1 ? 'day' : 'days'}
                  </span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[10px] uppercase font-bold">Demand Horizon</span>
                  <span className="font-mono font-medium text-slate-700">
                    {alert.projectedDemandBeforeExpiry === undefined ? 'Not available' : `~${alert.projectedDemandBeforeExpiry} units`}
                  </span>
                </div>
                <div>
                  <span className="text-slate-400 block text-[10px] uppercase font-bold">Value at Risk</span>
                  <span className="font-mono font-bold text-[#062314]">
                    {alert.wholesaleValueAtRisk === undefined ? 'Not available' : `$${alert.wholesaleValueAtRisk.toFixed(2)}`}
                  </span>
                </div>
              </div>

              {/* Model Evidence */}
              <div className="p-3 rounded-xl bg-slate-50 border border-slate-200/80 text-xs text-slate-600 mb-4">
                <span className="font-bold text-slate-900 block mb-0.5">Statistical Evidence:</span>
                {alert.modelEvidence}
              </div>
            </div>

            {/* Cross link CTA */}
            {alert.relatedRecommendationId ? (
              <button
                onClick={() =>
                  onNavigateToRecommendation &&
                  onNavigateToRecommendation(alert.relatedRecommendationId!)
                }
                className="w-full py-2 px-3 rounded-xl bg-emerald-50 hover:bg-emerald-100 text-emerald-900 border border-emerald-300 text-xs font-bold flex items-center justify-center gap-1.5 transition-colors cursor-pointer"
              >
                <span>View Candidate Recommendation</span>
                <svg className="w-3.5 h-3.5 text-emerald-700" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M14 5l7 7m0 0l-7 7m7-7H3" />
                </svg>
              </button>
            ) : (
              <div className="text-center text-[11px] text-slate-400 py-1">
                Decay rate under observation
              </div>
            )}
          </div>
        ))}
      </div>
      {!loading && !error && filteredAlerts.length === 0 && (
        <div className="rounded-xl border border-slate-200 bg-white p-5 text-sm text-slate-600">
          The backend returned no expiry alerts for this store and filter.
        </div>
      )}
    </div>
  );
};
